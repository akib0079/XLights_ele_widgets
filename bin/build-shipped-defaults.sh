#!/usr/bin/env bash
# Regenerate includes/Setup/data/shipped-defaults.php: the default content of
# every earlier plugin version (one run per commit of the plugin; snapshots that
# cannot load are skipped). Needs git and a WordPress install for wp-cli.
#   WP="wp --path=/srv/www" bin/build-shipped-defaults.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SLUG="xlights-elementor-widgets"
WP="${WP:-wp}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
OUT="$ROOT/$SLUG/includes/Setup/data/shipped-defaults.php"
mkdir -p "$(dirname "$OUT")"
COMMITS="$(git -C "$ROOT" log --format=%h -- "$SLUG")"
for c in $COMMITS; do
	git -C "$ROOT" archive "$c" "$SLUG" | tar -x -C "$TMP" --one-top-level="$c"
	if $WP eval-file "$ROOT/bin/shipped-defaults-harness.php" "$TMP/$c/$SLUG" "$ROOT/$SLUG/includes/Setup/Stale_Defaults.php" --skip-plugins --skip-themes > "$TMP/$c.json" 2> "$TMP/$c.err"; then
		echo "$c ok ($(wc -c < "$TMP/$c.json") bytes)"
	else
		echo "$c skipped: $(head -c 300 "$TMP/$c.err")"
		rm -f "$TMP/$c.json"
	fi
done
php -r '
$all = array();
foreach (glob($argv[1] . "/*.json") as $f) {
	$d = json_decode(file_get_contents($f), true);
	if (!is_array($d)) continue;
	foreach ($d as $k => $h) { $all[$k][$h] = true; }
}
ksort($all);
$out = "<?php\n/**\n * Generated by bin/build-shipped-defaults.sh — do not edit.\n * Control ID => hashes of the defaults earlier versions shipped.\n *\n * @package XLights\n */\n\ndefined( \"ABSPATH\" ) || exit;\n\nreturn array(\n";
foreach ($all as $k => $hs) { $out .= "\t" . var_export($k, true) . " => array( \x27" . implode("\x27, \x27", array_keys($hs)) . "\x27 ),\n"; }
$out .= ");\n";
file_put_contents($argv[2], $out);
echo count($all) . " controls\n";
' "$TMP" "$OUT"
